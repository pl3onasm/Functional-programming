module UsePictures where

import Pictures

-----------------------------------------------------------
-- Exercise 2.1 

blackHorse :: Picture
blackHorse =  invertColour horse

rotatedHorse :: Picture
rotatedHorse = rotate horse

-----------------------------------------------------------
-- Exercise 2.2

fourSquares :: Picture 
fourSquares = above (white `beside` black) 
                    (black `beside` white)

fourSquares' :: Picture
fourSquares' = beside (white `above` black)
                      (black `above` white)

chessRow :: Picture
chessRow = beside (fourSquares `beside` fourSquares)
                  (fourSquares `beside` fourSquares)

chessBoard :: Picture
chessBoard = above (chessRow `above` chessRow)
                   (chessRow `above` chessRow)

-----------------------------------------------------------
-- Exercise 2.3

variant1 :: Picture
variant1 = above (horse `beside` invertColour horse)
                 (invertColour horse `beside` horse)

variant2 :: Picture
variant2 = 
  beside (horse `above` (flipV (invertColour horse)))
         ((invertColour horse) `above` (flipV horse))

variant3 :: Picture
variant3 = 
  beside (horse `above` (rotate (invertColour horse)))
         ((invertColour horse) `above` (rotate horse))

-----------------------------------------------------------
-- Exercise 2.4

variant4 :: Picture
variant4 = 
  beside (horse `above` (flipH (invertColour horse)))
         ((invertColour horse) `above` (flipH horse))


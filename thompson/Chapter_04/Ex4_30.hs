-- | Builds a n-length column of alternating black and 
-- white squares, starting with a black square at the top
bwCol :: Integer -> Picture
bwCol n
  | n <= 1    = black
  | otherwise = black `above` wbCol (n - 1)

-- | Builds a n-length column of alternating black and 
-- white squares, starting with a white square at the top
wbCol :: Integer -> Picture
wbCol n
  | n <= 1    = white
  | otherwise = white `above` bwCol (n - 1)

-- | Builds a n x n chessboard pattern 
-- | using earlier defined functions
chessBoard :: Integer -> Picture
chessBoard n
  | n <= 0    = error "chessBoard: non-positive size"
  | n == 1    = black   -- smallest chessboard
  | otherwise = chessBoard (n - 1) `beside` col `above` row
    where row = if even n then wbRow n else bwRow n
          col = if even n then wbCol (n-1) else bwCol (n-1)

-- | Alternative solution for a n x n chessboard pattern
chessBoard' :: Integer -> Picture
chessBoard' n
  | n <= 0    = error "chessBoard: non-positive size"
  | otherwise = rows 0
  where
    rows r
      | r == n - 1 = cols r 0          
      | otherwise  = cols r 0 `above` rows (r + 1)
    cols r c
      | c == n - 1 = if alt then black else white
      | alt        = black `beside` cols r (c + 1)
      | otherwise  = white `beside` cols r (c + 1)
      where alt = even (r + c)


